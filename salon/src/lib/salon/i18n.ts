export type MsgKey = keyof typeof fr;

const tables: Record<Locale, Record<MsgKey, string>> = { fr, en };

export function translate(locale: Locale, key: MsgKey, vars?: Record<string, string | number>) {
  let text = tables[locale][key] ?? tables.fr[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

export function useT() {
  const locale = useSalon((s) => s.locale);
  const setLocale = useSalon((s) => s.setLocale);
  return {
    locale,
    setLocale,
    t: (key: MsgKey, vars?: Record<string, string | number>) => translate(locale, key, vars),
  };
}
