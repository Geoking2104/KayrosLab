export function t(locale, keyPath, fallback = '') {
  const keys = keyPath.split('.');
  let val = translations[locale];
  for (const k of keys) {
    if (val == null) return fallback;
    val = val[k];
  }
  return val ?? fallback;
}

export function useI18n(locale) {
  return {
    locale,
    t: (key, fallback) => t(locale, key, fallback),
    isRtl: false,
  };
}
